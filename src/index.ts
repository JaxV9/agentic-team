async function commitMessage(phase: string, items: string): Promise<{ msg: string; cost: number; tokens: number }> {
    try {
        const { content, cost, tokens } = await invokeGuardedLlm([
            ["system", AgentGIT],
            ["user", `Phase: ${phase}\nChanged files:\n${items}`],
        ]);
        const first = String(content)
            .split("\n")
            .map((l) => l.replace(/^[`"'\s]+|[`"'\s]+$/g, ""))
            .find(Boolean);
        if (first && /^(feat|fix|docs|test|chore)(\([a-z-]+\))?: .+/.test(first)) {
            return { msg: first.slice(0, 72), cost, tokens };
        }
        return { msg: FALLBACK_MSG[phase] ?? `chore: ${phase}`, cost, tokens };
    } catch {
        return { msg: FALLBACK_MSG[phase] ?? `chore: ${phase}`, cost: 0, tokens: 0 };
    }
}

async function commitPhase(phase: string, forcedMessage?: string): Promise<{ msg: string; cost: number; tokens: number }> {
    git("add", "-A");
    const files = git("diff", "--cached", "--name-only").split("\n").filter(Boolean);
    if (files.length === 0) return { msg: "nothing to commit", cost: 0, tokens: 0 };
    const envLeak = files.some((f) => /(^|\/)\.env(\.|$)/.test(f) && !f.endsWith(".env.example"));
    if (envLeak || SECRET_STRICT.test(git("diff", "--cached", "-U0"))) {
        git("reset");
        throw new Error(`Secret detected before commit (${phase}); commit aborted, files unstaged.`);
    }
    let cost = 0;
    let tokens = 0;
    let msg = forcedMessage;
    if (!msg) {
        const cm = await commitMessage(phase, files.join("\n"));
        msg = cm.msg;
        cost = cm.cost;
        tokens = cm.tokens;
    }
    git("commit", "-m", msg);
    log(`commit: ${msg}`);
    return { msg, cost, tokens };
}

/* ───────────────────────────── Agent Invocation & Payload Parsing ───────────────────────────── */

function balancedObject(text: string, start: number): string | null {
    let depth = 0;
    let inStr = false;
    let esc = false;
    for (let i = start; i < text.length; i++) {
        const c = text.charAt(i);
        if (inStr) {
            if (esc) esc = false;
            else if (c === "\\") esc = true;
            else if (c === '"') inStr = false;
            continue;
        }
        if (c === '"') inStr = true;
        else if (c === "{") depth++;
        else if (c === "}") {
            depth--;
            if (depth === 0) return text.slice(start, i + 1);
        }
    }
    return null;
}

function extractPayload(text: string): Payload | null {
    const starts: number[] = [];
    for (let i = text.length - 1; i >= 0 && starts.length < 60; i--) if (text.charAt(i) === "{") starts.push(i);
    for (const i of starts) {
        const json = balancedObject(text, i);
        if (!json) continue;
        try {
            const o = JSON.parse(json) as Record<string, unknown>;
            if (typeof o.status === "string") {
                return { status: o.status, defects: Array.isArray(o.defects) ? (o.defects as Defect[]) : [] };
            }
        } catch {
            /* try the previous candidate */
        }
    }
    return null;
}

async function runAgent(name: string, system: string, user: string, valid: string[]) {
    let accCost = 0;
    let accTokens = 0;
    for (let attempt = 1; attempt <= 2; attempt++) {
        log(`${name}: running (attempt ${attempt})`);
        const { content: text, cost, tokens } = await invokeGuardedLlm([
            ["system", `${system}\n\n${OUTPUT_RULES}`],
            ["user", user],
        ]);
        accCost += cost;
        accTokens += tokens;
        const payload = extractPayload(text);
        if (payload && valid.includes(payload.status)) {
            const written = writeFilesFromOutput(text);
            log(`${name}: ${payload.status}, ${written.length} file(s) written`);
            return { payload, written, cost: accCost, tokens: accTokens };
        }
        log(`${name}: missing or invalid status JSON`);
    }
    throw new Error(`${name}: no valid status after 2 attempts (expected one of ${valid.join(", ")})`);
}

async function runFiles(name: string, system: string, user: string): Promise<{ written: string[]; cost: number; tokens: number }> {
    log(`${name}: running (files only)`);
    const { content: text, cost, tokens } = await invokeGuardedLlm([
        ["system", `${system}\n\n${OUTPUT_RULES}`],
        ["user", user],
    ]);
    const written = writeFilesFromOutput(text);
    log(`${name}: ${written.length} file(s) written`);
    return { written, cost, tokens };
}

/* ───────────────────────────── Loop Control ───────────────────────────── */

function nodeFor(t?: string): string | null {
    const s = (t ?? "").toLowerCase();
    if (s.includes("backend")) return "agentBackend";
    if (s.includes("frontend")) return "agentFrontend";
    if (s.includes("architect")) return "agentArchitect";
    return null;
}

function reject(s: S, p: Payload, who: string) {
    const iteration = s.iteration + 1;
    const route = nodeFor(p.defects.find((d) => nodeFor(d.target_agent))?.target_agent);
    if (iteration >= MAX_REJECTIONS || !route) {
        const why = !route ? "no valid target agent" : `${MAX_REJECTIONS} rejections reached`;
        log(`ESCALATION to human (${who}: ${p.status}, ${why})`);
        return {
            status: p.status, defects: p.defects, iteration, route: "END", remediationTarget: "none",
            logs: [`${who} ${p.status} -> HUMAN_ESCALATION (${why})`],
        };
    }
    log(`${who} ${p.status} (rejection ${iteration}/${MAX_REJECTIONS}) -> ${route}`);
    return {
        status: p.status, defects: p.defects, iteration, route,
        remediationTarget: route.replace("agent", ""),
        logs: [`${who} ${p.status} -> ${route}`],
    };
}

