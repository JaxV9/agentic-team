/* ───────────────────────────── Layer 3 Guardrails: Kill Switch Logic ───────────────────────────── */

/**
 * Evaluates budget and step counters against safety thresholds.
 */
export function evaluateKillSwitch(s: {
    cumulativeCost?: number;
    stepCount?: number;
    killSwitchTriggered?: boolean;
    error?: string;
}): { triggered: boolean; reason: string } {
    if (s.killSwitchTriggered || globalKillSwitchTriggered) {
        return {
            triggered: true,
            reason: s.error || globalKillSwitchReason || "Emergency Kill Switch already active",
        };
    }
    if ((s.cumulativeCost ?? 0) >= MAX_BUDGET) {
        const reason = `Budget limit exceeded: cumulative cost ($${(s.cumulativeCost ?? 0).toFixed(4)}) >= MAX_BUDGET ($${MAX_BUDGET.toFixed(4)})`;
        activateGlobalKillSwitch(reason);
        return { triggered: true, reason };
    }
    if ((s.stepCount ?? 0) >= MAX_STEPS) {
        const reason = `Step limit reached: step count (${s.stepCount ?? 0}) >= MAX_STEPS (${MAX_STEPS})`;
        activateGlobalKillSwitch(reason);
        return { triggered: true, reason };
    }
    return { triggered: false, reason: "" };
}

/**
 * Estimates token count and USD cost for a DeepSeek model invocation.
 */
export function estimateCallCost(
    inputChars: number,
    outputChars: number,
    usage?: { input_tokens?: number; output_tokens?: number }
): { tokens: number; cost: number } {
    const inputTokens = usage?.input_tokens ?? Math.ceil(inputChars / 4);
    const outputTokens = usage?.output_tokens ?? Math.ceil(outputChars / 4);
    const totalTokens = inputTokens + outputTokens;
    const cost = inputTokens * DEEPSEEK_COST_PER_INPUT_TOKEN + outputTokens * DEEPSEEK_COST_PER_OUTPUT_TOKEN;
    return { tokens: totalTokens, cost };
}

async function invokeGuardedLlm(messages: [string, string][]): Promise<{
    content: string;
    cost: number;
    tokens: number;
}> {
    const safeMessages = await sanitizeMessagesWithPiiGuardrails(messages);
    const inputChars = safeMessages.reduce((sum, [, content]) => sum + content.length, 0);

    const res = await llm.invoke(safeMessages);
    const text = String(res.content);
    const outputChars = text.length;

    const { tokens, cost } = estimateCallCost(
        inputChars,
        outputChars,
        res.usage_metadata as { input_tokens?: number; output_tokens?: number } | undefined
    );

    return { content: text, cost, tokens };
}

