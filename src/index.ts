/* ───────────────────────────── Files ───────────────────────────── */

function safePath(rel: string): string | null {
    const abs = resolve(WORKDIR, rel.trim());
    if (abs !== WORKDIR && !abs.startsWith(WORKDIR + sep)) return null;
    if (relative(WORKDIR, abs).split(sep)[0] === ".git") return null;
    return abs;
}

// Writes every "### FILE: path" block emitted in an agent response; returns written file paths
function writeFilesFromOutput(out: string): string[] {
    const written: string[] = [];
    const re = /###\s*FILE:\s*(.+?)\s*\n(`{3,})[^\n]*\n([\s\S]*?)\n\2[ \t]*(?=\n|$)/g;
    for (const m of out.matchAll(re)) {
        const rel = m[1];
        const body = m[3];
        if (!rel || body === undefined) continue;
        const abs = safePath(rel.replace(/^`+|`+$/g, ""));
        if (!abs) {
            log(`ignored unsafe path: ${rel}`);
            continue;
        }
        mkdirSync(dirname(abs), { recursive: true });
        writeFileSync(abs, body.endsWith("\n") ? body : body + "\n", "utf-8");
        written.push(relative(WORKDIR, abs));
    }
    return written;
}

function readDocs(paths: string[], maxEach = DOC_BUDGET): string {
    return paths
        .map((p) => {
            const abs = safePath(p);
            if (!abs || !existsSync(abs)) return "";
            let t = readFileSync(abs, "utf-8");
            if (t.length > maxEach) t = t.slice(0, maxEach) + "\n[...truncated]";
            return `=== ${p} ===\n${t}`;
        })
        .filter(Boolean)
        .join("\n\n");
}

const SKIP_DIRS = new Set(["node_modules", ".git", "dist", "build", "coverage", ".next", "docs", ".venv", "__pycache__"]);
const TEXT_EXT = /\.(ts|tsx|js|jsx|mjs|cjs|json|py|html|css|scss|sql|prisma|vue|svelte|ya?ml)$/i;
const SKIP_FILES = /(package-lock\.json|pnpm-lock\.yaml|yarn\.lock)$/;

function listSource(dir = WORKDIR, out: string[] = []): string[] {
    for (const name of readdirSync(dir).sort()) {
        const abs = join(dir, name);
        const st = statSync(abs);
        if (st.isDirectory()) {
            if (!SKIP_DIRS.has(name)) listSource(abs, out);
        } else if (TEXT_EXT.test(name) && !SKIP_FILES.test(name) && st.size < 60_000) {
            out.push(abs);
        }
    }
    return out;
}

function readSource(budget = SOURCE_BUDGET): string {
    let used = 0;
    let omitted = 0;
    const parts: string[] = [];
    for (const f of listSource()) {
        const text = `=== ${relative(WORKDIR, f)} ===\n${readFileSync(f, "utf-8")}`;
        if (used + text.length > budget) {
            omitted++;
            continue;
        }
        used += text.length;
        parts.push(text);
    }
    if (omitted) parts.push(`[${omitted} source file(s) omitted: context budget reached]`);
    return parts.join("\n\n");
}

/* ───────────────────────────── Shell, scanners, tests ───────────────────────────── */

function sh(cmd: string, cwd: string, timeout = 180_000): { code: number | null; out: string } {
    const r = spawnSync(cmd, { shell: true, cwd, encoding: "utf-8", timeout });
    const out = `${r.stdout ?? ""}${r.stderr ?? ""}${r.error ? `\n${r.error.message}` : ""}`;
    return { code: r.status, out };
}

const SECRET_LINE =
    /(AKIA[0-9A-Z]{16}|-----BEGIN [A-Z ]*PRIVATE KEY-----|(api[_-]?key|secret|token|passw(or)?d)\s*[:=]\s*['"][^'"\s]{8,}['"])/i;
const SECRET_STRICT = /^\+.*(AKIA[0-9A-Z]{16}|-----BEGIN [A-Z ]*PRIVATE KEY-----|ghp_[A-Za-z0-9]{30,}|sk-[A-Za-z0-9]{32,})/m;

function runScanners(): string {
    const parts: string[] = [];
    const subdirs = readdirSync(WORKDIR)
        .map((n) => join(WORKDIR, n))
        .filter((p) => !SKIP_DIRS.has(basename(p)) && statSync(p).isDirectory());
    for (const d of [WORKDIR, ...subdirs]) {
        if (!existsSync(join(d, "package.json"))) continue;
        const r = sh("npm audit --omit=dev", d, 120_000);
        parts.push(`--- npm audit (${relative(WORKDIR, d) || "."}), exit ${r.code}\n${r.out.slice(0, 3000)}`);
    }
    const hits = listSource().flatMap((f) =>
        readFileSync(f, "utf-8")
            .split("\n")
            .map((l, i) => (SECRET_LINE.test(l) ? `${relative(WORKDIR, f)}:${i + 1}` : ""))
            .filter(Boolean),
    );
    parts.push(`--- secret scan\n${hits.length ? hits.join("\n") : "no matches"}`);
    if (existsSync(join(WORKDIR, ".env"))) parts.push("--- WARNING: a .env file exists in the project root");
    return parts.join("\n\n");
}

