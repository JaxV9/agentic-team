/**
 * Email PII detector.
 * Strategy: "redact" masks email addresses to prevent sensitive personal data leaks.
 */
export const emailPiiGuardrail = piiMiddleware("email", {
    strategy: "redact",
    applyToInput: true,
});

/**
 * API key detector (regex /sk-[a-zA-Z0-9]{32}/g).
 * Strategy: "block" aborts execution immediately if an API key is detected in prompts.
 */
export const apiKeyPiiGuardrail = piiMiddleware("api_key", {
    detector: /sk-[a-zA-Z0-9]{32}/g,
    strategy: "block",
    applyToInput: true,
});

async function runBeforeModelHook(middleware: any, state: any, runtime: any): Promise<any> {
    if (!middleware?.beforeModel) return;
    if (typeof middleware.beforeModel === "function") {
        return await middleware.beforeModel(state, runtime);
    }
    if (typeof middleware.beforeModel?.hook === "function") {
        return await middleware.beforeModel.hook(state, runtime);
    }
}

/**
 * Sanitizes input messages using LangChain PII middlewares.
 * Redacts emails and blocks API keys before requests are sent to DeepSeek.
 */
export async function sanitizeMessagesWithPiiGuardrails(
    messages: [string, string][]
): Promise<[string, string][]> {
    const sanitized: [string, string][] = [];
    for (const [role, content] of messages) {
        const fakeState = { messages: [new HumanMessage(content)] };
        const fakeRuntime = { context: { applyToInput: true } };

        await runBeforeModelHook(apiKeyPiiGuardrail, fakeState, fakeRuntime);
        const redactResult = await runBeforeModelHook(emailPiiGuardrail, fakeState, fakeRuntime);
        const safeContent = redactResult?.messages?.[0]?.content
            ? String(redactResult.messages[0].content)
            : content;

        sanitized.push([role, safeContent]);
    }
    return sanitized;
}

