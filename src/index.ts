/* ───────────────────────────── Graph & Conditional Routing ───────────────────────────── */

/**
 * Central conditional router.
 * Evaluates the Kill Switch exit condition before every state transition:
 * immediately forces transition to END if MAX_BUDGET or MAX_STEPS is reached.
 */
const routeFromState = (s: S): string => {
    const ks = evaluateKillSwitch(s);
    if (ks.triggered) {
        log(`🚨 [Kill Switch] Emergency threshold reached (${ks.reason}) -> forced transition to END`);
        return END;
    }
    return !s.route || s.route === "END" ? END : s.route;
};

